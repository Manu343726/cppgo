// Command benchtable turns `go test -bench` output into the comparison table
// in benchmarks/README.md.
//
// It reads one or more saved runs, each under the arm label whose file it was
// passed as, and renders every benchmark group as a table: median ns/op across
// the -count runs, the min–max range the same runs produced, bytes and
// allocations per operation, and the ratio against the group's go_direct arm.
// The README is rewritten between its generated markers; nothing in it is
// typed by hand.
//
// The input files are the raw stdout of `go test -run '^$' -bench . -benchmem
// -count=N`, one per arm, so a reader can re-derive every number:
//
//	benchtable -write README.md gobase=results/gobase.txt \
//	    cppgo=results/cppgo.txt cgo=results/cgo.txt
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"math"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Markers delimiting the generated region. The surrounding prose is written by
// hand; everything between them is produced by this command.
const (
	beginTable = "<!-- BEGIN TABLE (generated by cmd/benchtable) -->"
	endTable   = "<!-- END TABLE -->"
	beginEnv   = "<!-- BEGIN ENVIRONMENT (generated by cmd/benchtable) -->"
	endEnv     = "<!-- END ENVIRONMENT -->"
)

// armOrder is the column order of the comparison: the Go baselines first, then
// cgo, then cppgo's carriers. An arm not named here sorts after these,
// alphabetically, so a new arm is never dropped from the output.
var armOrder = []string{
	"go_direct",
	"go_indirect",
	"cgo",
	"cgo_thunk",
	"cppgo",
	"cppgo_direct",
	"cppgo_thunk",
}

// groupOrder is the order the benchmarks are presented in: the crossing floor
// first, then the constructs, then the failure paths and the lifecycle. An
// unknown group sorts after these, alphabetically.
var groupOrder = []string{
	"BenchmarkCall",
	"BenchmarkMidpoint",
	"BenchmarkBlend",
	"BenchmarkDescribe",
	"BenchmarkDoubled/n=8",
	"BenchmarkDoubled/n=1024",
	"BenchmarkThrow",
	"BenchmarkStatusOK",
	"BenchmarkStatusFailure",
	"BenchmarkReentrant",
	"BenchmarkObjectNewClose",
	"BenchmarkObjectGet",
}

// groupNotes is what each group measures, in one line. The prose lives here
// rather than in README.md so a group cannot be present in the table without
// the sentence that says what it is.
var groupNotes = map[string]string{
	"BenchmarkCall":           "the crossing floor: `bench::add(int64,int64)` and `bench::add_thunk`, the same arithmetic with and without `noexcept`",
	"BenchmarkMidpoint":       "a 16-byte POD by value in and out: `bench::midpoint(Point,Point)`",
	"BenchmarkBlend":          "a 24-byte POD by value with a result above the register class: `bench::blend(Sample,Sample,double) noexcept`",
	"BenchmarkDescribe":       "`std::string_view` in, `std::string` out: `bench::describe`",
	"BenchmarkDoubled/n=8":    "`std::vector<double>` in and out, 8 elements: `bench::doubled`",
	"BenchmarkDoubled/n=1024": "`std::vector<double>` in and out, 1024 elements: `bench::doubled`",
	"BenchmarkThrow":          "the throwing failure path: `bench::ratio(a, 0)` throws `std::domain_error`",
	"BenchmarkStatusOK":       "the `-status` convention's success path: `bench::parse(\"bench\")` returns 0",
	"BenchmarkStatusFailure":  "the `-status` convention's failure path: `bench::parse(\"!bench\")` returns 3",
	"BenchmarkReentrant":      "the C++ → Go round trip: `bench::fold(fn, 3, 4)` calls the Go function once",
	"BenchmarkObjectNewClose": "the object lifecycle: construct an opaque `bench::Counter`, then destroy it",
	"BenchmarkObjectGet":      "one method call on a live object: `bench::Counter::get() const noexcept`",
}

// sample is one benchmark line: the numbers one `go test` run reported.
type sample struct {
	ns     float64
	bytes  float64
	allocs float64
}

// stats aggregates every -count run of one (group, arm) pair.
type stats struct {
	ns     []float64
	bytes  []float64
	allocs []float64
}

// lineRE matches the benchmark lines go test prints with -benchmem. The CPU
// suffix (-16, and whatever GOMAXPROCS is on another machine) is stripped
// before the name is split, so a run on any machine aligns with another.
var lineRE = regexp.MustCompile(`^(Benchmark\S+)\s+(\d+)\s+([0-9.]+)\s+ns/op\s+([0-9.]+)\s+B/op\s+([0-9.]+)\s+allocs/op$`)

// cpuSuffixRE is the "-16" go test appends for GOMAXPROCS. It is a property of
// the machine, not of the benchmark, and must not leak into the table.
var cpuSuffixRE = regexp.MustCompile(`-\d+$`)

func main() {
	write := flag.String("write", "", "README.md to rewrite in place; empty writes the rendered blocks to stdout")
	envPath := flag.String("env", "", "file of `key: value` lines describing the machine and the run, rendered into the environment block")
	dbg := flag.Bool("v", false, "report each input file and the number of benchmark lines read")
	flag.Parse()

	if flag.NArg() == 0 {
		fatal(errors.New("usage: benchtable [-write README.md] [-env environment.txt] arm=file.txt [arm=file.txt ...]"))
	}

	groupArms := map[string]map[string]*stats{}
	for _, arg := range flag.Args() {
		arm, path, ok := strings.Cut(arg, "=")
		if !ok || arm == "" || path == "" {
			fatal(fmt.Errorf("bad input %q: want arm=file.txt", arg))
		}
		n, err := readFile(path, arm, groupArms)
		if err != nil {
			fatal(err)
		}
		if *dbg {
			fmt.Fprintf(os.Stderr, "%s: %d benchmark lines from %s\n", arm, n, path)
		}
	}

	if len(groupArms) == 0 {
		fatal(errors.New("no benchmark lines found: was -benchmem passed and -run set to '^$'?"))
	}

	table := renderTable(groupArms)
	if *write == "" {
		fmt.Print(table)
		if *envPath != "" {
			env, err := renderEnvironment(*envPath)
			if err != nil {
				fatal(err)
			}
			fmt.Print(env)
		}
		return
	}
	if err := rewrite(*write, beginTable, endTable, table); err != nil {
		fatal(err)
	}
	if *envPath != "" {
		env, err := renderEnvironment(*envPath)
		if err != nil {
			fatal(err)
		}
		if err := rewrite(*write, beginEnv, endEnv, env); err != nil {
			fatal(err)
		}
	}
}

// renderEnvironment turns the run's recorded facts into the block the README
// shows beside the table. The lines are copied verbatim: they are the
// investigation, not a summary of it.
func renderEnvironment(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()

	var b strings.Builder
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		fmt.Fprintf(&b, "- %s\n", line)
	}
	if err := scanner.Err(); err != nil {
		return "", err
	}
	if b.Len() == 0 {
		return "", fmt.Errorf("%s: the environment file is empty", path)
	}
	return b.String(), nil
}

// readFile parses one arm's saved run into groupArms and returns the number of
// benchmark lines it contributed. A file that produced nothing is a command
// that silently measured nothing, and is an error rather than an empty column.
func readFile(path, arm string, groupArms map[string]map[string]*stats) (int, error) {
	file, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer file.Close()

	lines := 0
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		m := lineRE.FindStringSubmatch(strings.TrimSpace(scanner.Text()))
		if m == nil {
			continue // goos:, pkg:, cpu:, PASS, ok, and anything else
		}
		name := cpuSuffixRE.ReplaceAllString(m[1], "")
		// A nested sub-benchmark ("BenchmarkDoubled/n=8/cppgo") names the arm
		// last, so the group is everything before the final slash.
		group, armName := name, "default"
		if slash := strings.LastIndex(name, "/"); slash >= 0 {
			group, armName = name[:slash], name[slash+1:]
		}
		s := &sample{
			ns:     mustFloat(m[3]),
			bytes:  mustFloat(m[4]),
			allocs: mustFloat(m[5]),
		}
		if groupArms[group] == nil {
			groupArms[group] = map[string]*stats{}
		}
		if groupArms[group][armName] == nil {
			groupArms[group][armName] = &stats{}
		}
		saved := groupArms[group][armName]
		saved.ns = append(saved.ns, s.ns)
		saved.bytes = append(saved.bytes, s.bytes)
		saved.allocs = append(saved.allocs, s.allocs)
		lines++
	}
	if err := scanner.Err(); err != nil {
		return lines, err
	}
	if lines == 0 {
		return 0, fmt.Errorf("%s: no benchmark lines; the arm %q measured nothing", path, arm)
	}
	return lines, nil
}

// renderTable renders every group in groupOrder, then any group the order does
// not name, alphabetically.
func renderTable(groupArms map[string]map[string]*stats) string {
	groups := orderedGroups(groupArms)
	var b strings.Builder
	for _, group := range groups {
		arms := orderedArms(groupArms[group])
		note := groupNotes[group]
		if note == "" {
			note = "no description"
		}
		fmt.Fprintf(&b, "### `%s`\n\n%s\n\n", group, note)
		b.WriteString("| arm | median ns/op | min–max ns/op | B/op | allocs/op | vs `go_direct` |\n")
		b.WriteString("|---|---:|---:|---:|---:|---:|\n")

		var baseline float64
		if goDirect := groupArms[group]["go_direct"]; goDirect != nil {
			baseline = median(goDirect.ns)
		}
		for _, arm := range arms {
			s := groupArms[group][arm]
			nsMedian := median(s.ns)
			ratio := "—"
			if baseline > 0 && s.ns != nil {
				ratio = fmt.Sprintf("%.2f×", nsMedian/baseline)
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s–%s | %s | %s | %s |\n",
				arm,
				formatNS(nsMedian),
				formatNS(minOf(s.ns)),
				formatNS(maxOf(s.ns)),
				formatCount(median(s.bytes)),
				formatCount(median(s.allocs)),
				ratio,
			)
		}
		fmt.Fprintf(&b, "\n%d run(s) per arm; medians, and the spread of the same runs.\n\n", len(groupArms[group][arms[0]].ns))
	}
	return b.String()
}

// orderedGroups is groupOrder first, then whatever else appeared, sorted.
func orderedGroups(groupArms map[string]map[string]*stats) []string {
	seen := map[string]bool{}
	var groups []string
	for _, group := range groupOrder {
		if _, ok := groupArms[group]; ok {
			groups = append(groups, group)
			seen[group] = true
		}
	}
	var rest []string
	for group := range groupArms {
		if !seen[group] {
			rest = append(rest, group)
		}
	}
	sort.Strings(rest)
	return append(groups, rest...)
}

// orderedArms is armOrder first, then any other arm of this group, sorted.
func orderedArms(arms map[string]*stats) []string {
	seen := map[string]bool{}
	var ordered []string
	for _, arm := range armOrder {
		if _, ok := arms[arm]; ok {
			ordered = append(ordered, arm)
			seen[arm] = true
		}
	}
	var rest []string
	for arm := range arms {
		if !seen[arm] {
			rest = append(rest, arm)
		}
	}
	sort.Strings(rest)
	return append(ordered, rest...)
}

// rewrite replaces the region between begin and end in path, leaving every
// other byte untouched. Both markers must be present exactly once: a README
// that lost one is not a README this command may guess its way through.
func rewrite(path, begin, end, content string) error {
	original, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	text := string(original)
	start := strings.Index(text, begin)
	if start < 0 {
		return fmt.Errorf("%s: marker %q is missing", path, begin)
	}
	finish := strings.Index(text, end)
	if finish < 0 || finish < start {
		return fmt.Errorf("%s: marker %q is missing", path, end)
	}
	replaced := text[:start+len(begin)] + "\n\n" + strings.TrimRight(content, "\n") + "\n\n" + text[finish:]

	// A second write of the same run must produce the same bytes: that is what
	// makes `make table` idempotent and the committed file reviewable.
	if replaced == text {
		return nil
	}
	return os.WriteFile(path, []byte(replaced), 0o644)
}

func median(values []float64) float64 {
	if len(values) == 0 {
		return math.NaN()
	}
	sorted := append([]float64(nil), values...)
	sort.Float64s(sorted)
	mid := len(sorted) / 2
	if len(sorted)%2 == 1 {
		return sorted[mid]
	}
	return (sorted[mid-1] + sorted[mid]) / 2
}

func minOf(values []float64) float64 {
	if len(values) == 0 {
		return math.NaN()
	}
	minimum := values[0]
	for _, value := range values[1:] {
		if value < minimum {
			minimum = value
		}
	}
	return minimum
}

func maxOf(values []float64) float64 {
	if len(values) == 0 {
		return math.NaN()
	}
	maximum := values[0]
	for _, value := range values[1:] {
		if value > maximum {
			maximum = value
		}
	}
	return maximum
}

// formatNS keeps small values readable and large ones short. Every number in
// the table is a median of real runs; the precision is presentation only.
func formatNS(ns float64) string {
	switch {
	case math.IsNaN(ns):
		return "—"
	case ns < 10:
		return strconv.FormatFloat(ns, 'f', 2, 64)
	case ns < 1000:
		return strconv.FormatFloat(ns, 'f', 1, 64)
	default:
		return strconv.FormatFloat(ns, 'f', 0, 64)
	}
}

func formatCount(value float64) string {
	if math.IsNaN(value) {
		return "—"
	}
	return strconv.FormatFloat(value, 'f', 0, 64)
}

func mustFloat(text string) float64 {
	value, err := strconv.ParseFloat(text, 64)
	if err != nil {
		fatal(fmt.Errorf("parsing %q: %w", text, err))
	}
	return value
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "benchtable: %v\n", err)
	os.Exit(1)
}
