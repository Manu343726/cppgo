package cppgo

import (
	"errors"
	"fmt"
	"path/filepath"

	"github.com/Manu343726/cppgo/internal/elfdeps"
	"github.com/Manu343726/cppgo/internal/rtl"
)

// preload loads an extracted set bottom-up, so every object's DT_NEEDED entries
// resolve to the copies the program carries.
//
// The loader matches a dependency by name against the objects it already holds,
// and it matches a loaded object through its DT_SONAME. Loading the set in
// dependency order is therefore what makes a transitive dependency resolve from
// the extraction directory: the object that declares the name is mapped before
// the loader reaches the entry that asks for it. A dependency the set does not
// carry is left to the dynamic loader's own search, and one that search cannot
// find either is an error naming it and the two ways to provide it.
//
// The requested object is loaded here too, once: the handle it is returned with is
// the one the caller's Library owns, and the rest of the handles belong to that
// same Library, which closes them when it is closed. The objects stay mapped
// exactly as long as the object that needs them, and no longer.
//
// A set generated by cppgo carries every object below the shim, so a shim's
// dependency is always found among the objects preloaded before it. The check
// cannot see an object the program loaded before this call, which the generated
// deployment never relies on.
func preload(dir string, objects []object, requested string) (*rtl.Library, []*rtl.Library, error) {
	read := make(map[string]*elfdeps.Object, len(objects))
	for _, o := range objects {
		path := filepath.Join(dir, o.name)
		obj, err := elfdeps.Read(path)
		if err != nil {
			// A set member that is not a shared object is reported the way the
			// loader reports it, as the object that could not be opened.
			return nil, nil, &OpenError{Path: path, Err: err}
		}
		read[o.name] = obj
	}

	resolver := elfdeps.Resolver{}

	// loaded is the set of sonames the loader can now match a NEEDED entry
	// against. An object without a soname never enters it: the loader cannot
	// match one by name, which the check below reports rather than hides.
	loaded := make(map[string]bool, len(objects))

	var wanted *rtl.Library

	handles := make([]*rtl.Library, 0, len(objects))
	for _, name := range preloadOrder(objects, read) {
		obj := read[name]

		for _, needed := range obj.Needed {
			if loaded[needed] {
				continue
			}
			if _, ok := resolver.Resolve(obj, needed); ok {
				continue
			}

			return nil, nil, errors.Join(&DependencyError{Object: name, Name: needed}, unload(handles))
		}

		handle, err := rtl.Preload(obj.Path)
		if err != nil {
			return nil, nil, errors.Join(fmt.Errorf("cppgo: preload the embedded set: %w", err), unload(handles))
		}
		if name == requested {
			wanted = handle
		} else {
			handles = append(handles, handle)
		}
		if obj.SOName != "" {
			loaded[obj.SOName] = true
		}
	}

	return wanted, handles, nil
}

// preloadOrder returns the file names of an extracted set in load order: every
// object after the objects its DT_NEEDED entries name.
//
// The edges are matched by soname and by file name, because one flat extraction
// directory holds both spellings. It is an ordering only: an object without a
// soname is still ordered before the object that needs it, but the loader cannot
// match it by name and preload checks that separately.
func preloadOrder(objects []object, read map[string]*elfdeps.Object) []string {
	byName := make(map[string]string, 2*len(objects))
	for _, o := range objects {
		byName[o.name] = o.name
		if soname := read[o.name].SOName; soname != "" {
			byName[soname] = o.name
		}
	}

	var order []string

	// state is 1 while an object is on the stack and 2 once it is placed, which
	// is also what keeps a cycle from recursing.
	state := make(map[string]int, len(objects))

	var visit func(name string)
	visit = func(name string) {
		if state[name] != 0 {
			return
		}
		state[name] = 1
		for _, needed := range read[name].Needed {
			if dep, ok := byName[needed]; ok {
				visit(dep)
			}
		}
		state[name] = 2
		order = append(order, name)
	}

	for _, o := range objects {
		visit(o.name)
	}

	return order
}

// unload closes the preload handles a failed preload had already taken, joining
// whatever the loader reports with the failure that made the caller give up.
func unload(handles []*rtl.Library) error {
	errs := make([]error, 0, len(handles))
	for _, handle := range handles {
		errs = append(errs, handle.Close())
	}

	return errors.Join(errs...)
}
