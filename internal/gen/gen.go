// Package gen implements cppgo's header-first code generator: it reads C++
// headers through internal/cxx and writes, for one Go package,
//
//   - zz_cppgo.gen.go, the only API a caller sees;
//   - zz_cppgo_amd64.s, one NOSPLIT trampoline per binding, whether it reaches
//     the user's symbol directly or the generated thunk — a reentrant binding
//     has none, because it enters C through runtime.cgocall — plus cppgoFree
//     when a result is a heap copy the Go side releases;
//   - zz_cppgo_shim.h and zz_cppgo_shim.cpp, one extern "C" thunk per binding
//     the direct ABI cannot call, which cppgo compiles itself into
//     libcppgo_<pkg>.so.
//
// Every binding is assigned exactly one carrier before anything is emitted. A
// declaration that is noexcept, non-virtual, defined out of line and register
// representable takes the direct trampoline; every other declaration gets a
// generated thunk. The carrier is invisible in the Go API and named in the
// report and in the binding's evidence comment. Nothing generated enters the
// user's build: the shim is compiled here, and the user's library is linked
// against, never edited.
//
// A class or function template is emitted twice. Phase one writes the generic Go
// declaration, which compiles with no concrete type. Phase two, `cppgo build
// -scan <go package>`, loads the program with go/packages, collects the
// instantiations it type-checks, and adds one thunk per member to the shim
// before compiling it. The thunk's own call instantiates the member; no
// class-level explicit instantiation is written. An instantiation the shim was
// not built for fails when it is used and names the `template ...;` line to add.
package gen

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// GeneratedBanner marks every file the generator writes.
const GeneratedBanner = "// Code generated by cppgo gen. DO NOT EDIT."

// Instantiation is one concrete template specialization the two-phase scan
// collected from a Go program: the qualified C++ template name and the Go type
// arguments of the instantiation, in declaration order.
type Instantiation struct {
	Template string
	Args     []string
}

// Names of the generated files. They are part of the contract: the generated
// package, the shim and a stale check all find each other by these names.
const (
	GenFileName        = "zz_cppgo.gen.go"
	AsmFileName        = "zz_cppgo_amd64.s"
	ShimHeaderFileName = "zz_cppgo_shim.h"
	ShimSourceFileName = "zz_cppgo_shim.cpp"
)

// ShimDirName is the subdirectory of the output directory that holds the
// shim's two sources.
//
// A Go package directory cannot contain C++ sources. The go tool refuses a
// directory with a .cpp in it unless the package uses cgo, and cppgo's packages
// never do. The shim is cppgo's own translation unit anyway. It lives one level
// down, where the go tool ignores it, and only the compiled libcppgo_<pkg>.so
// sits beside the generated Go.
const ShimDirName = "cppgo_shim"

// ShimPath is where one of the shim's sources is written under outDir.
func ShimPath(outDir, name string) string { return filepath.Join(outDir, ShimDirName, name) }

// CppgoImportPath is the import path of the runtime package in generated code.
const CppgoImportPath = "github.com/Manu343726/cppgo"

// Config controls one generator run. It is the binding manifest.
type Config struct {
	// Headers are the C++ headers to bind, in the order given with -header.
	Headers []string
	// Package is the Go package name.
	Package string
	// Library is the shared object Open loads when no path is given. When it
	// is a readable file its dynamic symbol table is the cross-check for every
	// direct binding.
	Library string
	// Libraries are the other shared objects the shim links against. A slice
	// that spans several modules of one library names each: the shim records
	// them all as DT_NEEDED, so a symbol from any of them resolves when the
	// shim is loaded, and the first remains the one the package loads. Library
	// is the first of the list.
	Libraries []string
	// Out is the directory the generated files are written to.
	Out string
	// Check verifies that the generated files are up to date instead of
	// writing them.
	Check bool
	// CompileCommands is the -compile-commands value.
	CompileCommands string
	// Bind adds a root. With no Bind every public declaration is a root.
	Bind []string
	// Exclude removes a root. An unmatched entry is an error.
	Exclude []string
	// Instantiate names the concrete template specializations the API uses,
	// e.g. "mathx::Box<int>". An instantiation must be visible to libclang as
	// an explicit instantiation or a reachable type.
	Instantiate []string
	// Rename maps a qualified name or signature to a Go name.
	Rename []string
	// Status names the declarations whose 32-bit return is a status code, from
	// -status. Their Go signature returns only an error: nothing is emitted for
	// the integer, and a non-zero value is the failure.
	Status []string
	// Scan names the Go packages the two-phase flow parses to collect the
	// template instantiations a program uses, from -scan. Empty means the
	// generic API is emitted with no concrete shim.
	Scan []string
	// ScanDir is the directory the -scan patterns resolve against, from
	// -scan-dir. Empty means the process's working directory.
	ScanDir string
	// Instantiation is one concrete specialization the two-phase scan found.
	// It is filled from Scan, not from the command line.
	Instantiation []Instantiation
	// CXX is the C++ compiler the shim is built with, from -cxx. Empty means
	// g++, then clang++.
	CXX string
	// Report receives one line per binding. Nil discards it.
	Report io.Writer
	// Warnings receives package-level warnings. Nil discards them.
	Warnings io.Writer
	// Coverage, when set, names the file the per-declaration coverage report is
	// written to. It is one of the generated outputs, so check compares it.
	Coverage string
	// Alias names a library template that is an alias of a standard-library one,
	// written <C++ template>=<std template>: OpenCV's cv::Ptr<T> is
	// std::shared_ptr<T>, and the model reads the alias as the standard shape.
	Alias []string
	// Proxy names the container a parameter is carried as, for a declaration
	// whose parameter is an InputArray/OutputArray proxy: the shim constructs
	// the proxy around the container, so one thunk holds both. The entries are
	// written <declaration>@<index>=<C++ type>.
	Proxy []string
}

// Output is one generated file. Subdir is the directory under the output
// directory it belongs in. It is empty for the package's own files, and
// ShimDirName for the shim's sources.
type Output struct {
	Name   string
	Subdir string
	Data   []byte
}

// Result is everything one generator run produced.
type Result struct {
	// Outputs are the files to write, sorted by name.
	Outputs []Output
	// Report is the per-binding carrier report.
	Report []string
	// Warnings are package-level remarks for stderr.
	Warnings []string
}

// Render parses the headers described by cfg and returns the files Generate
// would write, sorted by name. It writes no file.
func Render(cfg Config) ([]Output, error) {
	result, err := RenderResult(cfg)
	if err != nil {
		return nil, err
	}
	return result.Outputs, nil
}

// RenderResult is Render with the report and the warnings one run produces.
func RenderResult(cfg Config) (*Result, error) {
	model, err := build(cfg)
	if err != nil {
		return nil, err
	}
	return renderModel(model)
}

// renderModel turns a built model into the four output files. It is separate
// from RenderResult so the emitters can be exercised with a model a header
// cannot produce.
func renderModel(model *packageModel) (*Result, error) {
	goFile, err := model.emitGo()
	if err != nil {
		return nil, err
	}
	asmFile := model.emitAsm()
	shimHeader, shimSource, spans, err := model.emitShim()
	if err != nil {
		return nil, err
	}
	model.spans = spans
	outs := []Output{
		{Name: GenFileName, Data: goFile},
		{Name: AsmFileName, Data: asmFile},
		{Name: ShimHeaderFileName, Subdir: ShimDirName, Data: shimHeader},
		{Name: ShimSourceFileName, Subdir: ShimDirName, Data: shimSource},
	}
	if model.cfg.Coverage != "" {
		outs = append(outs, Output{
			Name: filepath.Base(model.cfg.Coverage),
			Data: model.coverage,
		})
	}
	sort.Slice(outs, func(i, j int) bool { return outs[i].Name < outs[j].Name })
	return &Result{
		Outputs:  outs,
		Report:   model.report(),
		Warnings: model.warnings(),
	}, nil
}

// Generate writes the generated files and compiles the shim, or verifies the
// files in check mode. Check mode writes no file and builds no shim. The shim
// is a build artifact, and what a stale check measures is the sources.
func Generate(cfg Config) error {
	model, err := build(cfg)
	if err != nil {
		return err
	}
	result, err := renderModel(model)
	if err != nil {
		return err
	}
	outDir := cfg.Out
	if outDir == "" {
		outDir = "."
	}
	if cfg.Warnings != nil {
		for _, warning := range result.Warnings {
			fmt.Fprintf(cfg.Warnings, "cppgo: warning: %s\n", warning)
		}
	}
	if cfg.Check {
		return checkOutputs(outDir, result.Outputs)
	}
	// The shim is compiled in a scratch directory first. A generation that
	// cannot build its own shim writes nothing: the output directory is only
	// touched once the artifact exists.
	scratch, err := os.MkdirTemp("", "cppgo-shim-")
	if err != nil {
		return fmt.Errorf("cppgo: creating the shim build directory: %w", err)
	}
	if os.Getenv("CPPGO_KEEP_SCRATCH") != "" {
		fmt.Fprintf(os.Stderr, "cppgo: scratch %s\n", scratch)
	} else {
		defer func() { _ = os.RemoveAll(scratch) }()
	}
	if err := writeOutputs(scratch, result.Outputs); err != nil {
		return err
	}
	shim, err := model.buildShim(scratch)
	if err != nil {
		return err
	}
	model.build = shim
	if err := writeOutputs(outDir, result.Outputs); err != nil {
		return err
	}
	built, err := os.ReadFile(shim.Path)
	if err != nil {
		return fmt.Errorf("cppgo: reading the compiled shim %s: %w", shim.Path, err)
	}
	shim.Path = filepath.Join(outDir, filepath.Base(shim.Path))
	if err := os.WriteFile(shim.Path, built, 0o755); err != nil {
		return fmt.Errorf("cppgo: writing %s: %w", shim.Path, err)
	}
	if cfg.Report != nil {
		for _, line := range result.Report {
			fmt.Fprintln(cfg.Report, line)
		}
		fmt.Fprintf(cfg.Report, "cppgo: built %s with %s\n", shim.Path, shim.Compiler)
	}
	return nil
}

// writeOutputs writes every generated file.
func writeOutputs(outDir string, outputs []Output) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("creating output directory %s: %w", outDir, err)
	}
	for _, o := range outputs {
		path := filepath.Join(outDir, o.Subdir, o.Name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return fmt.Errorf("creating %s: %w", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, o.Data, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return nil
}

// checkOutputs reports every generated file that is missing or stale.
func checkOutputs(outDir string, outputs []Output) error {
	var stale []string
	for _, o := range outputs {
		old, err := os.ReadFile(filepath.Join(outDir, o.Subdir, o.Name))
		if err != nil || !bytes.Equal(old, o.Data) {
			stale = append(stale, o.Name)
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("%s is out of date (run \"cppgo gen\"): %s", outDir, strings.Join(stale, ", "))
	}
	return nil
}

// invocation is the exact command line that produced the package, written into
// the generated Go file so the regeneration command lives in the repository.
func (c Config) invocation() string {
	parts := []string{"cppgo gen"}
	for _, header := range c.Headers {
		parts = append(parts, "-header "+header)
	}
	parts = append(parts, "-package "+c.Package, "-library "+c.Library)
	if c.Out != "" {
		parts = append(parts, "-out "+c.Out)
	}
	if c.CompileCommands != "" {
		parts = append(parts, "-compile-commands "+c.CompileCommands)
	}
	for _, bind := range c.Bind {
		parts = append(parts, "-bind "+bind)
	}
	for _, exclude := range c.Exclude {
		parts = append(parts, "-exclude "+exclude)
	}
	for _, instantiate := range c.Instantiate {
		parts = append(parts, "-instantiate "+instantiate)
	}
	for _, rename := range c.Rename {
		parts = append(parts, "-rename "+rename)
	}
	for _, status := range c.Status {
		parts = append(parts, "-status "+status)
	}
	return strings.Join(parts, " ")
}
