// Package v3 implements cppgo's header-first code generator.
//
// It reads C++ headers through internal/cxx and emits, for one Go package:
//
//   - zz_cppgo.gen.go, the only API a caller sees;
//   - zz_cppgo_amd64.s, one NOSPLIT trampoline per binding;
//   - zz_cppgo_shim.h and zz_cppgo_shim.cpp, one extern "C" thunk per binding
//     the direct ABI cannot call.
//
// Every binding is assigned exactly one carrier before anything is emitted: the
// direct trampoline when the declaration is noexcept, not virtual, defined out
// of line, and register representable, and a generated thunk everywhere else.
// The carrier is invisible in the Go API and named in the report and in the
// binding's evidence comment.
package gen

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// GeneratedBanner marks every file the generator writes.
const GeneratedBanner = "// Code generated by cppgo gen. DO NOT EDIT."

// Names of the generated files. They are part of the contract: the shim is
// compiled by the user's build, and Open names it when a thunk is missing.
const (
	GenFileName        = "zz_cppgo.gen.go"
	AsmFileName        = "zz_cppgo_amd64.s"
	ShimHeaderFileName = "zz_cppgo_shim.h"
	ShimSourceFileName = "zz_cppgo_shim.cpp"
)

// CppgoImportPath is the import path of the runtime package in generated code.
const CppgoImportPath = "github.com/Manu343726/cppgo"

// Config controls one generator run. It is the binding manifest.
type Config struct {
	// Headers are the C++ headers to bind, in the order given with -header.
	Headers []string
	// Package is the Go package name.
	Package string
	// Library is the shared object Open loads when no path is given. When it
	// is a readable file its dynamic symbol table is the cross-check for every
	// direct binding.
	Library string
	// Out is the directory the generated files are written to.
	Out string
	// Check verifies that the generated files are up to date instead of
	// writing them.
	Check bool
	// CompileCommands is the -compile-commands value.
	CompileCommands string
	// Bind adds a root. With no Bind every public declaration is a root.
	Bind []string
	// Exclude removes a root. An unmatched entry is an error.
	Exclude []string
	// Instantiate names the concrete template specialisations the API uses,
	// e.g. "mathx::Box<int>". An instantiation must be visible to libclang as
	// an explicit instantiation or a reachable type.
	Instantiate []string
	// Rename maps a qualified name or signature to a Go name.
	Rename []string
	// Report receives one line per binding. Nil discards it.
	Report io.Writer
	// Warnings receives package-level warnings. Nil discards them.
	Warnings io.Writer
}

// Output is one generated file.
type Output struct {
	Name string
	Data []byte
}

// Result is everything one generator run produced.
type Result struct {
	// Outputs are the files to write, sorted by name.
	Outputs []Output
	// Report is the per-binding carrier report.
	Report []string
	// Warnings are package-level remarks for stderr.
	Warnings []string
}

// Render parses the headers described by cfg and returns the files Generate
// would write, sorted by name. Nothing is written to disk.
func Render(cfg Config) ([]Output, error) {
	result, err := RenderResult(cfg)
	if err != nil {
		return nil, err
	}
	return result.Outputs, nil
}

// RenderResult is Render with the report and the warnings one run produces.
func RenderResult(cfg Config) (*Result, error) {
	model, err := build(cfg)
	if err != nil {
		return nil, err
	}
	return renderModel(model)
}

// renderModel turns a built model into the four output files. It is separate
// from RenderResult so the emitters can be exercised with a model a header
// cannot produce.
func renderModel(model *packageModel) (*Result, error) {
	goFile, err := model.emitGo()
	if err != nil {
		return nil, err
	}
	asmFile := model.emitAsm()
	shimHeader, shimSource, spans, err := model.emitShim()
	if err != nil {
		return nil, err
	}
	if err := model.validateShim(shimHeader, shimSource, spans); err != nil {
		return nil, err
	}
	outs := []Output{
		{Name: GenFileName, Data: goFile},
		{Name: AsmFileName, Data: asmFile},
		{Name: ShimHeaderFileName, Data: shimHeader},
		{Name: ShimSourceFileName, Data: shimSource},
	}
	sort.Slice(outs, func(i, j int) bool { return outs[i].Name < outs[j].Name })
	return &Result{
		Outputs:  outs,
		Report:   model.report(),
		Warnings: model.warnings(),
	}, nil
}

// Generate writes the generated files, or verifies them in check mode.
func Generate(cfg Config) error {
	result, err := RenderResult(cfg)
	if err != nil {
		return err
	}
	outDir := cfg.Out
	if outDir == "" {
		outDir = "."
	}
	if cfg.Warnings != nil {
		for _, warning := range result.Warnings {
			fmt.Fprintf(cfg.Warnings, "cppgo: warning: %s\n", warning)
		}
	}
	if cfg.Report != nil {
		for _, line := range result.Report {
			fmt.Fprintln(cfg.Report, line)
		}
	}
	if cfg.Check {
		var stale []string
		for _, o := range result.Outputs {
			old, err := os.ReadFile(filepath.Join(outDir, o.Name))
			if err != nil || !bytes.Equal(old, o.Data) {
				stale = append(stale, o.Name)
			}
		}
		if len(stale) > 0 {
			return fmt.Errorf("%s is out of date (run \"cppgo gen\"): %s", outDir, strings.Join(stale, ", "))
		}
		return nil
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("creating output directory %s: %w", outDir, err)
	}
	for _, o := range result.Outputs {
		path := filepath.Join(outDir, o.Name)
		if err := os.WriteFile(path, o.Data, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return nil
}

// invocation is the exact command line that produced the package, written into
// the generated Go file so the regeneration command lives in the repository.
func (c Config) invocation() string {
	parts := []string{"cppgo gen"}
	for _, header := range c.Headers {
		parts = append(parts, "-header "+header)
	}
	parts = append(parts, "-package "+c.Package, "-library "+c.Library)
	if c.Out != "" {
		parts = append(parts, "-out "+c.Out)
	}
	if c.CompileCommands != "" {
		parts = append(parts, "-compile-commands "+c.CompileCommands)
	}
	for _, bind := range c.Bind {
		parts = append(parts, "-bind "+bind)
	}
	for _, exclude := range c.Exclude {
		parts = append(parts, "-exclude "+exclude)
	}
	for _, instantiate := range c.Instantiate {
		parts = append(parts, "-instantiate "+instantiate)
	}
	for _, rename := range c.Rename {
		parts = append(parts, "-rename "+rename)
	}
	return strings.Join(parts, " ")
}
