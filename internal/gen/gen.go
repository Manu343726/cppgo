// Package gen implements the cppgo code generator.
//
// The generator reads a Go package whose files carry two kinds of directive:
//
//	//cppgo:library libname       (once per package)
//	//cppgo:external symbol_name  (on the doc comment of a function)
//
// An optional //cppgo:mode shim may be written down explicitly; it is the only
// calling convention implemented, and any other mode is rejected rather than
// generating a binding that could not work.
//
// and writes four files:
//
//	zz_cppgo.gen.go     idiomatic Go wrappers, lazy library binding, and the
//	                    declarations of the assembly trampolines
//	zz_cppgo_amd64.s    one NOSPLIT trampoline per bound function
//	cppgo_shim.h        the extern "C" prototypes the C++ side implements
//	zz_cppgo_stub.go    the input file with every bound function body
//	                    replaced by a delegation to its wrapper
//
// # Where the fourth file goes
//
// The fourth file is a rewrite of the user's own source file, so if the input
// file already lives in the output directory the generator rewrites it in
// place instead of emitting a copy. That keeps the package compiling without
// deleting anything, and keeps regeneration idempotent: the directives stay
// where the user wrote them and running the generator twice produces the same
// bytes either way.
//
// # Calling convention
//
// Both halves of the boundary are generated from the same tables, so the
// convention is cppgo's own, modelled on SysV AMD64:
//
//   - integer and pointer arguments go to RDI, RSI, RDX, RCX, R8, R9 in
//     declaration order;
//   - float arguments go to XMM0-XMM7 in declaration order;
//   - a string or a slice is passed as (pointer, length), pointer first;
//   - the result comes back in AX (integer/pointer) or X0 (float).
//
// A function with a trailing error result returns int32_t instead: zero means
// success, anything else means the shim stored a message read with
// cppgo_last_error(). Any other result is then written through a trailing
// out-pointer, because the ABI only allows one return register.
package gen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// GeneratedBanner marks every file the generator writes.
const GeneratedBanner = "// Code generated by cppgo gen. DO NOT EDIT."

// Names of the generated files.
const (
	GenFileName    = "zz_cppgo.gen.go"
	AsmFileName    = "zz_cppgo_amd64.s"
	ShimFileName   = "cppgo_shim.h"
	SourceFileName = "zz_cppgo_stub.go"
)

// CppgoImportPath is the import path of the cppgo runtime package, as it
// appears in generated code.
const CppgoImportPath = "github.com/Manu343726/cppgo"

// Config controls a generator run.
type Config struct {
	// Dir is the package directory holding the directives. Required.
	Dir string
	// Out is the directory the generated files are written to. It defaults
	// to Dir, in which case the input files are rewritten in place.
	Out string
	// Check verifies that the generated files are up to date instead of
	// writing them.
	Check bool
}

// Output is one generated file.
type Output struct {
	Name string
	Data []byte
}

// Render parses the package described by cfg and returns the files Generate
// would write, sorted by name. Nothing is written to disk.
func Render(cfg Config) ([]Output, error) {
	dir := cfg.Dir
	if dir == "" {
		dir = "."
	}
	outDir := cfg.Out
	if outDir == "" {
		outDir = dir
	}
	absOut, err := filepath.Abs(outDir)
	if err != nil {
		return nil, fmt.Errorf("resolving output directory %s: %w", outDir, err)
	}

	pkg, err := parsePackage(dir)
	if err != nil {
		return nil, err
	}

	sigs := make([]*signature, len(pkg.Funcs))
	for i, f := range pkg.Funcs {
		sig, err := buildSignature(f)
		if err != nil {
			return nil, posErr(f.Pos, "%v", err)
		}
		sigs[i] = sig
	}

	genGo, err := emitGo(pkg, sigs)
	if err != nil {
		return nil, err
	}
	asm := emitAsm(sigs)
	shim := emitShim(pkg, sigs)

	outs := []Output{
		{Name: GenFileName, Data: genGo},
		{Name: AsmFileName, Data: asm},
		{Name: ShimFileName, Data: shim},
	}
	first := true
	for _, sf := range pkg.Files {
		inPlace := filepath.Dir(sf.Abs) == absOut
		name := filepath.Base(sf.Abs)
		if !inPlace {
			if first {
				name = SourceFileName
			} else {
				name = "zz_cppgo_stub_" + strings.TrimSuffix(filepath.Base(sf.Abs), ".go") + ".go"
			}
			first = false
		}
		data, err := emitSource(pkg, sf, !inPlace)
		if err != nil {
			return nil, err
		}
		outs = append(outs, Output{Name: name, Data: data})
	}
	sort.Slice(outs, func(i, j int) bool { return outs[i].Name < outs[j].Name })
	return outs, nil
}

// Generate writes the generated files, or verifies them in check mode.
func Generate(cfg Config) error {
	outs, err := Render(cfg)
	if err != nil {
		return err
	}
	outDir := cfg.Out
	if outDir == "" {
		outDir = cfg.Dir
	}
	if outDir == "" {
		outDir = "."
	}
	if cfg.Check {
		var stale []string
		for _, o := range outs {
			old, err := os.ReadFile(filepath.Join(outDir, o.Name))
			if err != nil || !bytes.Equal(old, o.Data) {
				stale = append(stale, o.Name)
			}
		}
		if len(stale) > 0 {
			return fmt.Errorf("%s is out of date (run \"cppgo gen\"): %s", outDir, strings.Join(stale, ", "))
		}
		return nil
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("creating output directory %s: %w", outDir, err)
	}
	for _, o := range outs {
		path := filepath.Join(outDir, o.Name)
		if err := os.WriteFile(path, o.Data, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return nil
}
