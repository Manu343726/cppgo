//go:build cppgo_targets

// Package gen's target smoke test parses the real headers of the three
// compatibility targets and binds a curated subset of each. It is the 4b-2
// evidence that the constructs the epic names are enough to reach those headers,
// and it records what still fails so the 4c slices know what they are up
// against.
//
// The libraries are looked up, in order, at:
//
//   - CPPGO_TARGETS_INCLUDE, a directory holding eigen3/, opencv4/ and af/;
//   - the Debian layout of the CI image (targets/e1efb00b847f).
//
// A library that is absent skips its own smoke with the reason, and names the
// package to install.
package gen

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Manu343726/cppgo/internal/cxx"
)

// targetsRoot is the include root the three libraries are read from.
func targetsRoot() string {
	if root := os.Getenv("CPPGO_TARGETS_INCLUDE"); root != "" {
		return root
	}
	for _, candidate := range []string{"/usr/local/include", "/usr/include"} {
		if _, err := os.Stat(filepath.Join(candidate, "eigen3")); err == nil {
			return candidate
		}
	}
	return ""
}

// smokeHeader is one library's curated slice.
type smokeHeader struct {
	// name is the library, as the report names it.
	name string
	// header is the real header, relative to the roots.
	header string
	// includes are the include directories the parse needs, relative to the
	// root.
	includes []string
	// bind are the declarations the subset names.
	bind []string
	// instantiate are the template specializations the subset names.
	instantiate []string
	// writableHeader, when set, is a wrapper the smoke writes beside the real
	// headers so an explicit instantiation exists for a template-only type.
	writableHeader string
	writableBody   string
	// expect are the Go declarations the subset must produce.
	expect []string
	// bindOptional marks a library whose curated subset is reported, not
	// required: the 4c slice owns it, and 4b-2 measures only that the header
	// parses and is modelled.
	bindOptional bool
	// install is the package a machine installs to run this smoke.
	install string
}

// TestTargetHeadersSmoke is the real-header smoke. It does not fail on a
// construct the emitter cannot carry yet: it reports what parses, what binds and
// what still fails, which is the whole point of running it before the slices.
func TestTargetHeadersSmoke(t *testing.T) {
	root := targetsRoot()
	if root == "" {
		t.Skip("no include root with the target libraries; set CPPGO_TARGETS_INCLUDE or install libeigen3-dev/libopencv-dev/libarrayfire-dev")
	}
	smokes := []smokeHeader{
		{
			name:     "eigen",
			header:   "eigen3/Eigen/Dense",
			includes: []string{".", "eigen3"},
			// Eigen is header-only and template-only: a concrete matrix exists
			// only when it is instantiated, which is what the two-phase flow
			// writes into the shim. The wrapper stands in for that line.
			writableHeader: "eigen3/cppgo_smoke_matrix.hpp",
			writableBody: "// Code generated by cppgo's target smoke test. DO NOT EDIT.\n" +
				"#pragma once\n#include <Eigen/Dense>\n" +
				"template struct Eigen::Matrix<double, 3, 3, 0, 3, 3>;\n",
			instantiate:  []string{"Eigen::Matrix<double,3,3,0,3,3>"},
			bind:         []string{"Eigen::Matrix<double,3,3,0,3,3>::rows"},
			bindOptional: true,
			install:      "libeigen3-dev",
		},
		{
			name:     "opencv",
			header:   "opencv4/opencv2/core.hpp",
			includes: []string{".", "opencv4"},
			bind:     []string{"cv::NormTypes", "cv::Mat::total"},
			expect:   []string{"type NormTypes", "NormTypesNORML2", "func (m *Mat) Total()"},
			install:  "libopencv-dev",
		},
		{
			name:     "arrayfire",
			header:   "af/array.h",
			includes: []string{"."},
			bind:     []string{"af_dtype"},
			expect:   []string{"type AfDtype", "AfDtypeF32"},
			install:  "libarrayfire-dev",
		},
	}
	for _, smoke := range smokes {
		smoke := smoke
		t.Run(smoke.name, func(t *testing.T) {
			t.Parallel()
			header := filepath.Join(root, smoke.header)
			if _, err := os.Stat(header); err != nil {
				t.Skipf("%s is not installed (%v); install %s", smoke.header, err, smoke.install)
			}
			runTargetSmoke(t, root, smoke, header)
		})
	}
}

// exportedOnly drops the generated package's own lower-case identifiers, which
// are machinery rather than API.
func exportedOnly(names []string) []string {
	out := make([]string, 0, len(names))
	for _, name := range names {
		if name == "" || name[0] < 'A' || name[0] > 'Z' {
			continue
		}
		out = append(out, name)
	}
	return out
}

// runTargetSmoke reports one library's three answers: what the parse found, what
// the curated subset bound, and what the whole header still refuses.
func runTargetSmoke(t *testing.T, root string, smoke smokeHeader, header string) {
	t.Helper()
	if smoke.writableHeader != "" {
		path := filepath.Join(root, smoke.writableHeader)
		if err := os.WriteFile(path, []byte(smoke.writableBody), 0o644); err != nil {
			t.Skipf("the smoke needs to write %s: %v", path, err)
		}
		t.Cleanup(func() { _ = os.Remove(path) })
		header = path
	}

	args := []string{"-std=c++17", "-xc++-header"}
	for _, include := range smoke.includes {
		// Absolute, because includeRoots matches the header's path against
		// them and a relative path is resolved against cppgo's own directory.
		args = append(args, "-I"+filepath.Join(root, include))
	}
	project, err := cxx.Open(cxx.Options{Header: header, Args: args})
	if err != nil {
		t.Fatalf("%s: parse: %v", smoke.name, err)
	}
	t.Cleanup(func() { _ = project.Close() })
	t.Logf("%s: parsed %s: %d symbols, %d records, %d enums", smoke.name, smoke.header,
		len(project.Symbols()), len(project.Records()), len(project.Enums()))

	// The curated subset: a header cppgo writes for the parse, so the include
	// paths are the library's own.
	dir := t.TempDir()
	database := filepath.Join(dir, "compile_commands.json")
	entry := []map[string]any{{
		"directory": dir,
		"file":      header,
		"arguments": append([]string{"clang++"}, append(args, "-c", header)...),
	}}
	encoded, err := json.Marshal(entry)
	if err != nil {
		t.Fatalf("%s: compile_commands: %v", smoke.name, err)
	}
	if err := os.WriteFile(database, encoded, 0o644); err != nil {
		t.Fatalf("%s: compile_commands: %v", smoke.name, err)
	}

	out := filepath.Join(dir, smoke.name)
	var report, warnings bytes.Buffer
	// Generate, not Render: a subset that binds but whose shim does not
	// compile is not bound, and the compile is what says so.
	err = Generate(Config{
		Headers:         []string{header},
		Package:         "target_" + smoke.name,
		Library:         "lib" + smoke.name,
		Out:             out,
		CompileCommands: database,
		Bind:            smoke.bind,
		Instantiate:     smoke.instantiate,
		Report:          &report,
		Warnings:        &warnings,
	})
	if err != nil {
		// This is the report the slices are written against, and a library
		// whose subset is optional is not a failure here.
		t.Logf("%s: the curated subset does not bind yet: %v", smoke.name, firstLine(err.Error()))
		reportSmokeRefusals(t, smoke, header, database)
		if smoke.bindOptional {
			return
		}
		t.Fatalf("%s: the curated subset does not bind: %v", smoke.name, err)
	}
	generatedBytes, readErr := os.ReadFile(filepath.Join(out, GenFileName))
	if readErr != nil {
		t.Fatalf("%s: the generated package is not there: %v", smoke.name, readErr)
	}
	generated := string(generatedBytes)
	var types, funcs []string
	for _, line := range strings.Split(generated, "\n") {
		switch {
		case strings.HasPrefix(line, "type "):
			name := strings.TrimSuffix(strings.TrimPrefix(line, "type "), " struct {")
			if i := strings.IndexAny(name, "[ "); i > 0 {
				name = name[:i]
			}
			types = append(types, name)
		case strings.HasPrefix(line, "func ") && !strings.HasPrefix(line, "func ("):
			name := strings.TrimPrefix(line, "func ")
			if i := strings.IndexAny(name, "( "); i > 0 {
				name = name[:i]
			}
			funcs = append(funcs, name)
		}
	}
	types = exportedOnly(types)
	funcs = exportedOnly(funcs)
	t.Logf("%s: the curated subset bound %d types and %d functions: %s", smoke.name,
		len(types), len(funcs), strings.Join(append(types, funcs...), ", "))
	if len(types)+len(funcs) == 0 {
		t.Fatalf("%s: the curated subset produced no binding", smoke.name)
	}
	// The declarations the subset names must be there by name.
	for _, want := range smoke.expect {
		if !strings.Contains(generated, want) {
			t.Errorf("%s: the curated subset lacks %q", smoke.name, want)
		}
	}
	for _, warning := range strings.Split(strings.TrimSpace(warnings.String()), "\n") {
		if warning != "" {
			t.Logf("%s: %s", smoke.name, warning)
		}
	}
	for _, line := range strings.Split(strings.TrimSpace(report.String()), "\n") {
		if line != "" {
			t.Logf("%s: bound %s", smoke.name, line)
		}
	}

	// The whole header, for what the 4c slice will face.
	reportSmokeRefusals(t, smoke, header, database)
}

// reportSmokeRefusals binds the whole header and logs the first refusal, which is
// what a slice that asks for everything hits first.
func reportSmokeRefusals(t *testing.T, smoke smokeHeader, header, database string) {
	t.Helper()
	_, err := RenderResult(Config{
		Headers:         []string{header},
		Package:         "target_" + smoke.name + "_all",
		Library:         "lib" + smoke.name,
		CompileCommands: database,
		Instantiate:     smoke.instantiate,
	})
	if err == nil {
		t.Logf("%s: the whole header binds", smoke.name)
		return
	}
	t.Logf("%s: the whole header still fails at: %s", smoke.name, firstLine(err.Error()))
}
