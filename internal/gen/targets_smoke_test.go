// TestTargetHeadersSmoke is the real-header smoke. It does not fail on a
// construct the emitter cannot carry yet: it reports what parses, what binds and
// what still fails, which is the whole point of running it before the slices.
func TestTargetHeadersSmoke(t *testing.T) {
	roots := targetsRoots()
	for _, smoke := range targetSmoke {
		smoke := smoke
		t.Run(smoke.name, func(t *testing.T) {
			t.Parallel()
			root, header, ok := findTarget(roots, smoke.header)
			if !ok {
				t.Skipf("%s is not installed; install %s", smoke.header, smoke.install)
			}
			runTargetSmoke(t, root, smoke, header)
		})
	}
}

// findTarget locates a library's header under the roots, in order.
func findTarget(roots []string, header string) (root, path string, ok bool) {
	for _, root := range roots {
		candidate := filepath.Join(root, header)
		if _, err := os.Stat(candidate); err == nil {
			return root, candidate, true
		}
	}
	return "", "", false
}

// targetArgs is the compiler command line the parse and the shim share: the
// language, and every include directory that exists under the root.
func targetArgs(root string, includes []string) []string {
	args := []string{"-std=c++17", "-xc++-header"}
	for _, include := range includes {
		// Absolute, because includeRoots matches the header's path against
		// them and a relative path is resolved against cppgo's own directory.
		args = append(args, "-I"+filepath.Join(root, include))
	}
	return args
}

// exportedOnly drops the generated package's own lower-case identifiers, which
// are machinery rather than API.
func exportedOnly(names []string) []string {
	out := make([]string, 0, len(names))
	for _, name := range names {
		if name == "" || name[0] < 'A' || name[0] > 'Z' {
			continue
		}
		out = append(out, name)
	}
	return out
}

// writeWrapper writes the smoke's wrapper header for one library into a
// directory of its own, and returns its path. A wrapper is written beside the
// real header nowhere: the roots are read-only on a machine where the library is
// installed, and the include directories the parse already has make the temp
// directory enough.
func writeWrapper(t *testing.T, smoke smokeHeader) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, smoke.name+"_smoke.hpp")
	if err := os.WriteFile(path, []byte(smoke.wrapper), 0o644); err != nil {
		t.Fatalf("the smoke needs to write %s: %v", path, err)
	}
	return path
}

// smokeHeaders is the header list one smoke parses: the real header, and the
// wrapper beside it.
//
// Both are needed, and for a reason that is not obvious. A library installed
// under a compiler's own system prefix (/usr/local/include for ArrayFire) is
// reached through a system directory, so its declarations count only when the
// named header is the file the parse was given — libclang's system-header answer
// is about the file, not the directory it lives in. Naming the real header makes
// its declarations part of the API; naming the wrapper makes the wrapper's own
// functions part of it. One parse of each, and the model merges them.
func smokeHeaders(wrapper, realHeader string) []string {
	if wrapper == "" || wrapper == realHeader {
		return []string{realHeader}
	}
	return []string{wrapper, realHeader}
}

// compileDatabase writes the compile_commands.json the parse and the shim build
// read, for one header and one command line.
func compileDatabase(t *testing.T, header string, args []string) string {
	t.Helper()
	dir := t.TempDir()
	database := filepath.Join(dir, "compile_commands.json")
	entry := []map[string]any{{
		"directory": dir,
		"file":      header,
		"arguments": append([]string{"clang++"}, append(args, "-c", header)...),
	}}
	encoded, err := json.Marshal(entry)
	if err != nil {
		t.Fatalf("compile_commands: %v", err)
	}
	if err := os.WriteFile(database, encoded, 0o644); err != nil {
		t.Fatalf("compile_commands: %v", err)
	}
	return database
}

// runTargetSmoke reports one library's three answers: what the parse found, what
// the curated subset bound, and what the whole header still refuses.
func runTargetSmoke(t *testing.T, root string, smoke smokeHeader, realHeader string) {
	t.Helper()
	header := realHeader
	if smoke.wrapper != "" {
		header = writeWrapper(t, smoke)
	}

	args := targetArgs(root, smoke.includes)
	// The wrapper's own directory is where the quoted include it writes is
	// found; the library's headers stay reachable through the root's -I.
	args = append(args, "-I"+filepath.Dir(header))
	// Exactly one `parsed <library>:` line per library is the report CI counts,
	// so the real header is the one that carries it. The wrapper's own parse is
	// logged separately: a library whose headers live under a compiler's system
	// prefix is only part of the API through the real header's parse, and the
	// wrapper is read for the functions it declares.
	for _, each := range smokeHeaders(header, realHeader) {
		project, err := cxx.Open(cxx.Options{Header: each, Args: args})
		if err != nil {
			t.Fatalf("%s: parse %s: %v", smoke.name, each, err)
		}
		if each == realHeader {
			t.Logf("%s: parsed %s: %d symbols, %d records, %d enums", smoke.name, smoke.header,
				len(project.Symbols()), len(project.Records()), len(project.Enums()))
		} else {
			t.Logf("%s: the smoke's wrapper %s parsed %d symbols, %d records, %d enums: what the library's own header cannot say",
				smoke.name, filepath.Base(each), len(project.Symbols()), len(project.Records()), len(project.Enums()))
		}
		_ = project.Close()
	}

	database := compileDatabase(t, header, args)
	out := filepath.Join(t.TempDir(), smoke.name)
	var report, warnings bytes.Buffer
	// Generate, not Render: a subset that binds but whose shim does not
	// compile is not bound, and the compile is what says so.
	err := Generate(Config{
		Headers:         smokeHeaders(header, realHeader),
		Package:         "target_" + smoke.name,
		Library:         "lib" + smoke.name,
		Out:             out,
		CompileCommands: database,
		Bind:            smoke.bind,
		Instantiate:     smoke.instantiate,
		Report:          &report,
		Warnings:        &warnings,
	})
	if err != nil {
		// This is the report the slices are written against, and a library
		// whose subset is optional is not a failure here.
		t.Logf("%s: the curated subset does not bind yet: %v", smoke.name, firstLine(err.Error()))
		reportSmokeRefusals(t, smoke, header, realHeader, database)
		if smoke.bindOptional {
			return
		}
		t.Fatalf("%s: the curated subset does not bind: %v", smoke.name, err)
	}
	generatedBytes, readErr := os.ReadFile(filepath.Join(out, GenFileName))
	if readErr != nil {
		t.Fatalf("%s: the generated package is not there: %v", smoke.name, readErr)
	}
	generated := string(generatedBytes)
	var types, funcs []string
	for _, line := range strings.Split(generated, "\n") {
		switch {
		case strings.HasPrefix(line, "type "):
			name := strings.TrimSuffix(strings.TrimPrefix(line, "type "), " struct {")
			if i := strings.IndexAny(name, "[ "); i > 0 {
				name = name[:i]
			}
			types = append(types, name)
		case strings.HasPrefix(line, "func ") && !strings.HasPrefix(line, "func ("):
			name := strings.TrimPrefix(line, "func ")
			if i := strings.IndexAny(name, "( "); i > 0 {
				name = name[:i]
			}
			funcs = append(funcs, name)
		}
	}
	types = exportedOnly(types)
	funcs = exportedOnly(funcs)
	t.Logf("%s: the curated subset bound %d types and %d functions: %s", smoke.name,
		len(types), len(funcs), strings.Join(append(types, funcs...), ", "))
	if len(types)+len(funcs) == 0 {
		t.Fatalf("%s: the curated subset produced no binding", smoke.name)
	}
	// The declarations the subset names must be there by name.
	for _, want := range smoke.expect {
		if !strings.Contains(generated, want) {
			t.Errorf("%s: the curated subset lacks %q", smoke.name, want)
		}
	}
	for _, warning := range strings.Split(strings.TrimSpace(warnings.String()), "\n") {
		if warning != "" {
			t.Logf("%s: %s", smoke.name, warning)
		}
	}
	for _, line := range strings.Split(strings.TrimSpace(report.String()), "\n") {
		if line != "" {
			t.Logf("%s: bound %s", smoke.name, line)
		}
	}

	// The whole header, for what the 4c slice will face.
	reportSmokeRefusals(t, smoke, header, realHeader, database)
}

// reportSmokeRefusals binds the whole header and logs the first refusal, which is
// what a slice that asks for everything hits first.
func reportSmokeRefusals(t *testing.T, smoke smokeHeader, header, realHeader, database string) {
	t.Helper()
	_, err := RenderResult(Config{
		Headers:         smokeHeaders(header, realHeader),
		Package:         "target_" + smoke.name + "_all",
		Library:         "lib" + smoke.name,
		CompileCommands: database,
		Instantiate:     smoke.instantiate,
	})
	if err == nil {
		t.Logf("%s: the whole header binds", smoke.name)
		return
	}
	t.Logf("%s: the whole header still fails at: %s", smoke.name, firstLine(err.Error()))
}

// TestTargetsByValueRoundTrip is the 4c acceptance against the real libraries:
// the target types cross the Go boundary by value and the values come back, so
// the block, the copy and the destructor are measured and not just emitted.
//
// It needs the shared objects, not only the headers: a library whose object is
// absent skips its own round trip with the reason.
func TestTargetsByValueRoundTrip(t *testing.T) {
	requireEndToEndTools(t)
	repo, err := filepath.Abs("../..")
	require := func(t *testing.T, err error) {
		t.Helper()
		if err != nil {
			t.Fatalf("the round trip needs the end-to-end tools: %v", err)
		}
	}
	for _, smoke := range targetSmoke {
		smoke := smoke
		if smoke.roundTrip == "" {
			continue
		}
		t.Run(smoke.name, func(t *testing.T) {
			root, realHeader, ok := findTarget(targetsRoots(), smoke.header)
			if !ok {
				t.Skipf("%s is not installed; install %s", smoke.header, smoke.install)
			}
			library := ""
			for _, candidate := range smoke.libraries {
				if _, err := os.Stat(candidate); err == nil {
					library = candidate
					break
				}
			}
			if len(smoke.libraries) > 0 && library == "" {
				t.Skipf("none of %s is installed; install %s", strings.Join(smoke.libraries, ", "), smoke.install)
			}
			require(t, err)

			header := realHeader
			if smoke.wrapper != "" {
				header = writeWrapper(t, smoke)
			}
			args := targetArgs(root, smoke.includes)
			args = append(args, "-I"+filepath.Dir(header))
			database := compileDatabase(t, header, args)

			moduleDir := t.TempDir()
			out := filepath.Join(moduleDir, "target_"+smoke.name)
			cfg := Config{
				Headers:         smokeHeaders(header, realHeader),
				Package:         "target_" + smoke.name,
				Library:         library,
				Out:             out,
				CompileCommands: database,
				Bind:            smoke.bind,
				Instantiate:     smoke.instantiate,
			}
			if err := Generate(cfg); err != nil {
				t.Fatalf("%s: the by-value subset does not bind: %v", smoke.name, err)
			}
			shim := filepath.Join(out, ShimLibraryName("target_"+smoke.name))
			if _, err := os.Stat(shim); err != nil {
				t.Fatalf("%s: the shim was not built: %v", smoke.name, err)
			}
			if library != "" {
				deployBeside(t, library, out)
			}
			if err := writeModule(t, moduleDir, repo); err != nil {
				t.Fatalf("%s: module: %v", smoke.name, err)
			}
			if err := os.WriteFile(filepath.Join(out, "byvalue_test.go"), []byte(smoke.roundTrip), 0o644); err != nil {
				t.Fatalf("%s: test source: %v", smoke.name, err)
			}
			env := []string{"CGO_ENABLED=0", "CPPGO_E2E_SHIM=" + shim, "AF_BACKEND=cpu"}
			ran := runGoEnv(t, goTool(t), moduleDir, env, "test", "-count=1", "-v", "./target_"+smoke.name)
			if !strings.Contains(ran, "--- PASS: TestByValue") {
				t.Fatalf("%s: the by-value round trip did not pass:\n%s", smoke.name, ran)
			}
		})
	}
}
