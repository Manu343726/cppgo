//go:build cppgo_targets

// Package gen's target smoke test parses the real headers of the three
// compatibility targets and binds a curated subset of each. It is the 4b-2
// evidence that the constructs the epic names are enough to reach those headers,
// and — since #102 — the 4c evidence that the constructs 4b-2 still missed are
// enough for the target types themselves to cross by value.
//
// The libraries are looked up, in order, at:
//
//   - CPPGO_TARGETS_INCLUDE, one or more directories separated by ':';
//   - the Debian layout of the CI image, /usr/local/include and /usr/include.
//
// A library that is absent skips its own smoke with the reason, and names the
// package to install.
package gen

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Manu343726/cppgo/internal/cxx"
)

// targetsRoots is the include roots the three libraries are read from.
func targetsRoots() []string {
	if root := os.Getenv("CPPGO_TARGETS_INCLUDE"); root != "" {
		var roots []string
		for _, entry := range filepath.SplitList(root) {
			if entry != "" {
				roots = append(roots, entry)
			}
		}
		return roots
	}
	return []string{"/usr/local/include", "/usr/include"}
}

// smokeHeader is one library's curated slice.
type smokeHeader struct {
	// name is the library, as the report names it.
	name string
	// header is the real header, relative to a root.
	header string
	// includes are the include directories the parse needs, relative to the
	// root.
	includes []string
	// bind are the declarations the subset names.
	bind []string
	// instantiate are the template specializations the subset names.
	instantiate []string
	// wrapper, when set, is a header the smoke writes beside the parse so a
	// construct the header alone cannot express exists: an explicit
	// instantiation, or a real call whose shape the target's own API takes.
	wrapper string
	// expect are the Go declarations the subset must produce.
	expect []string
	// bindOptional marks a library whose curated subset is reported, not
	// required: the 4c slice owns it, and 4b-2 measures only that the header
	// parses and is modelled.
	bindOptional bool
	// install is the package a machine installs to run this smoke.
	install string
	// libraries are the shared objects the round trip links against, first
	// existing one wins. Empty means the library is header-only.
	libraries []string
	// roundTrip is the Go program the by-value test runs, empty when this
	// library's subset has no by-value shape the round trip can measure.
	roundTrip string
}

