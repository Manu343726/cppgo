#!/usr/bin/env bash
#
# coverage-gate.sh — enforce the coverage contract in DESIGN.md
#   "Coverage gate: >= 99% on ./..., measured by scripts/coverage-gate.sh.
#    The exclusions are zz_cppgo*.go (generator output), internal/gen/testdata/
#    (generated fixtures) and internal/testlib/ (test scaffolding with no
#    tests of its own)."  cmd/ is measured too.
#
# Usage:
#   scripts/coverage-gate.sh [profile] [threshold]
#   scripts/coverage-gate.sh                       # coverage.out, 99.0
#   scripts/coverage-gate.sh coverage.out 98.5
#   COVER_PROFILE=... COVERAGE_THRESHOLD=... scripts/coverage-gate.sh
#
# The profile must be produced by, at minimum:
#   go test -race -covermode=atomic -coverprofile=coverage.out ./...
# (See `make cover`.)
#
# Exit codes: 0 = pass, 1 = below threshold, 2 = cannot measure.
# Uses only bash + awk + the go toolchain, so it runs unchanged in CI and
# locally on a bare runner image.

set -euo pipefail
export LC_ALL=C

PROFILE="${1:-${COVER_PROFILE:-coverage.out}}"
THRESHOLD="${2:-${COVERAGE_THRESHOLD:-99.0}}"

usage() {
  sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
}

case "${1:-}" in
  -h|--help)
    usage
    exit 0
    ;;
esac

if ! [[ $THRESHOLD =~ ^[0-9]+([.][0-9]+)?$ ]]; then
  echo "error: threshold '$THRESHOLD' is not a number (expected e.g. 99.0)" >&2
  exit 2
fi

if [[ ! -f $PROFILE ]]; then
  echo "error: coverage profile '$PROFILE' not found." >&2
  echo "       generate it with:" >&2
  echo "         go test -race -covermode=atomic -coverprofile=$PROFILE ./..." >&2
  echo "       or simply run: make cover    (make cover-gate does this for you)" >&2
  exit 2
fi

# ---------------------------------------------------------------------------
# Exclusions.
#
# DESIGN.md allows exactly two, and they are deliberate — not a convenience to
# make the number look good. Nothing else is excluded, and every rule here is
# echoed to the terminal below so a reader can see what was skipped. If you add
# a rule, add it here *with a reason*, never by filtering inside a pipeline.
#
#   1. generated code        zz_cppgo*.go (generator output, committed) and
#                            internal/gen/testdata/ (fixtures the generator
#                            writes and then diffs). Machine-written: coverage
#                            of them measures the generator's own test corpus,
#                            not hand-written behaviour.
#   2. test scaffolding      internal/testlib/ compiles the C++ fixture library
#                            that other tests load, and has no tests of its
#                            own; it is not shipped code.
#
# cmd/ is NOT excluded. The CLI is tested through run(args, stdout, stderr)
# with injected streams (see DESIGN.md), so it earns its coverage like any
# other package.
# ---------------------------------------------------------------------------
EXCLUDE_PATTERNS=(
  '(^|/)zz_cppgo[^/]*[.]go:'
  '(^|/)internal/gen/testdata/'
  '(^|/)internal/testlib/'
)
EXCLUDE_REASONS=(
  'zz_cppgo*.go is generated by `cppgo gen`'
  'internal/gen/testdata holds generated fixtures'
  'internal/testlib is test scaffolding (builds the C++ .so that other tests call), not shipped code'
)

exclude_re="$(printf '%s|' "${EXCLUDE_PATTERNS[@]}")"
exclude_re="${exclude_re%|}"

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
filtered="$tmpdir/coverage.filtered.out"

# Keep the "mode:" header, drop excluded files, count what went in/out.
awk -v re="$exclude_re" '
  NR == 1 { print; next }
  $0 ~ re { next }
  { print }
' "$PROFILE" >"$filtered"

# grep exits 1 on "no lines", which is a valid count of 0 under `set -e`.
total_blocks="$(grep -cv '^mode:' "$PROFILE" || true)"
kept_lines="$(grep -cv '^mode:' "$filtered" || true)"
skipped_lines=$(( ${total_blocks:-0} - ${kept_lines:-0} ))

if [[ ${kept_lines:-0} -eq 0 ]]; then
  echo "error: no coverage blocks left in '$PROFILE' after exclusions." >&2
  echo "       The test run produced no instrumented code — did the tests actually run?" >&2
  exit 2
fi

echo "coverage gate — profile: $PROFILE, threshold: ${THRESHOLD}%"
echo

# --- what was excluded (never silently) ------------------------------------
echo "Excluded (by contract in DESIGN.md):"
for i in "${!EXCLUDE_PATTERNS[@]}"; do
  printf '  - %-28s %s\n' "${EXCLUDE_PATTERNS[$i]}" "${EXCLUDE_REASONS[$i]}"
done
printf '  (%d block(s) skipped, %d measured)\n' "$skipped_lines" "$kept_lines"
echo

# --- total, parsed from `go tool cover -func` ------------------------------
if ! func_out="$(go tool cover -func="$filtered" 2>&1)"; then
  echo "error: 'go tool cover -func' failed on '$PROFILE':" >&2
  printf '%s\n' "$func_out" >&2
  echo "       (the profile records source paths — is the tree the one that produced it?)" >&2
  exit 2
fi
total_line="$(printf '%s\n' "$func_out" | grep -E '^total:' | tail -n 1 || true)"

total_pct=""
if [[ -n $total_line ]]; then
  total_pct="$(printf '%s\n' "$total_line" | awk '{print $NF}' | tr -d '%')"
fi

# --- per-package summary, statement-weighted, straight from the profile ----
# Profile line: <file>:<startLine>.<col>,<endLine>.<col> <numStmt> <count>
module_path="$(go list -m 2>/dev/null || echo "")"
pkg_table="$tmpdir/packages.txt"

awk -v mod="$module_path" -v t="$THRESHOLD" '
  NR == 1 { next }
  {
    loc = $1
    stmts = $2 + 0
    count = $3 + 0
    sub(/:[0-9]+\.[0-9]+,[0-9]+\.[0-9]+$/, "", loc)
    dir = loc
    sub(/\/[^\/]*$/, "", dir)
    if (mod != "" && dir == mod) dir = "."
    else if (mod != "" && index(dir, mod "/") == 1) dir = substr(dir, length(mod) + 2)
    if (dir == "") dir = "."
    total[dir] += stmts
    covered[dir] += 0
    if (count > 0) covered[dir] += stmts
  }
  END {
    for (d in total) {
      pct = (total[d] > 0) ? (100 * covered[d] / total[d]) : 0
      flag = (pct + 0 < t + 0) ? "  <-- below threshold" : ""
      printf "  %-46s %-14s %6.1f%%%s\n", d, covered[d] "/" total[d], pct, flag
    }
  }
' "$filtered" | sort -k1,1 >"$pkg_table"

echo "Per-package coverage (statements, weighted):"
printf '  %-46s %-14s %s\n' "PACKAGE" "STMTS" "COVER"
printf '  %s\n' "-------------------------------------------------------------------------"
cat "$pkg_table"

# --- lowest covered functions, so a failure is actionable ------------------
uncovered="$tmpdir/uncovered.txt"
uncovered_all="$tmpdir/uncovered.all"
printf '%s\n' "$func_out" \
  | grep -vE '^total:' \
  | awk '{ pct = $NF; sub(/%$/, "", pct); if (pct + 0 < 100) print pct "\t" $0 }' \
  | sort -n -k1,1 >"$uncovered_all" || true

if [[ -s $uncovered_all ]]; then
  uncovered_total="$(wc -l <"$uncovered_all" | tr -d ' ')"
  head -n 10 "$uncovered_all" >"$uncovered"
  echo
  if [[ $uncovered_total -gt 10 ]]; then
    echo "Functions below 100% (worst 10 of $uncovered_total shown):"
  else
    echo "Functions below 100% ($uncovered_total shown):"
  fi
  while IFS=$'\t' read -r _pct line; do
    printf '  %s\n' "$line"
  done <"$uncovered"
fi

# --- verdict ---------------------------------------------------------------
if [[ -z $total_pct ]]; then
  # Fall back to the statement-weighted number if -func produced no total line.
  total_pct="$(awk '
    NR == 1 { next }
    { s += $2; if ($3 + 0 > 0) c += $2 }
    END { printf "%.1f", (s > 0) ? (100 * c / s) : 0 }
  ' "$filtered")"
  echo
  echo "note: 'go tool cover -func' printed no total line; used the statement-weighted total instead."
fi

echo
if awk -v p="$total_pct" -v t="$THRESHOLD" 'BEGIN { exit (p + 0 >= t + 0) ? 0 : 1 }'; then
  printf '\033[1;32mPASS\033[0m total coverage %s%% >= %s%%\n' "$total_pct" "$THRESHOLD"
  exit 0
fi

printf '\033[1;31mFAIL\033[0m total coverage %s%% < %s%% (contract: DESIGN.md "Test and coverage contract")\n' "$total_pct" "$THRESHOLD" >&2
exit 1
