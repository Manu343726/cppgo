package cppgo

// Handle is an opaque reference to a foreign object: a C++ instance, a context,
// an iterator — anything whose layout the Go side must not know.
//
// It is a uintptr rather than a pointer on purpose. The memory it refers to is
// owned by the foreign side (or by a Go allocation whose layout mirrors it), and
// treating it as an unsafe.Pointer would invite the garbage collector and
// vet's unsafeptr check to reason about memory that is not Go's.
//
// # Lifetimes
//
// A Handle carries no ownership. Nothing frees the object when the Handle
// becomes unreachable, and the runtime will not keep anything alive on its
// behalf. For every constructor there must be a matching destroy on the foreign
// side, and the Go code is responsible for calling it:
//
//	type Vector struct{ h cppgo.Handle }
//
//	func NewVector(x, y float64) (*Vector, error) {
//		var out cppgo.Handle
//		if err := cppgoCreate(&out, x, y); err != nil {
//			return nil, err
//		}
//		return &Vector{h: out}, nil
//	}
//
//	func (v *Vector) Close() error { return cppgoDestroy(v.h) }
//
// A finalizer is deliberately not provided: finalizers run at unpredictable
// times on an arbitrary goroutine, which means they would call back into C++ at
// a moment when the library may already be closing.
//
// # Zero value
//
// The zero Handle (0) is the null pointer and is what a failing constructor
// leaves behind. Foreign code must reject it; a binding generated by cppgo
// never synthesizes a Handle.
type Handle uintptr

// IsNil reports whether h is the null handle.
func (h Handle) IsNil() bool { return h == 0 }
